ENGINE_VERSION = "0.1.7"
TICK = 0.25
HYPOTHETICAL_MULTIPLIER = 20.0
INITIAL_CASH = 1_000_000.0

CASES = {
    "gross": (0.0, 0.0),
    "cost": (2.5, 0.25),
    "stress": (2.5, 0.5),
    "stress4tick": (2.5, 1.0),
}


class LegalLimitFillExecutor(FillExecutor):
    """Reuse native fills, account and OCO; do not slip passive sell limits below limit."""

    def execute(self, order, base_price: float) -> bool:
        if order.order_type != OrderType.LIMIT:
            return super().execute(order, base_price)
        old = self.broker.slippage_model
        self.broker.slippage_model = NoSlippage()
        try:
            return super().execute(order, base_price)
        finally:
            self.broker.slippage_model = old


class LegalLimitsEngine(Engine):
    """Reviewed, version-pinned native fill extension. Do not monkeypatch site-packages."""

    def __init__(self, *args, **kwargs):
        installed = importlib.metadata.version("ml4t-backtest")
        if installed != ENGINE_VERSION:
            raise ValueError(f"ENGINE_VERSION_UNKNOWN: {installed} != {ENGINE_VERSION}")
        super().__init__(*args, **kwargs)
        broker = self.broker
        old = broker._fill_executor
        replacement = LegalLimitFillExecutor(
            broker, account=old.account, market=old.market, orders=old.orders,
            risk=old.risk, journal=old.journal, record_pnl=old.record_pnl
        )
        replacement.fill_engine = broker._fill_engine
        broker._fill_engine.executor = replacement
        broker._fill_executor = replacement


@dataclass(frozen=True)
class HistoricalNativeResult:
    status: str
    mode: str
    case: str
    fills: pl.DataFrame
    trades: pl.DataFrame
    equity: pl.DataFrame
    signals: tuple[dict[str, Any], ...]
    limitations: tuple[str, ...]


def _execute_registered_dukascopy(
    frame: pl.DataFrame, *, mode: str, case: str, permit_gate: GateReport
) -> HistoricalNativeResult:
    """Use only verified research permit and locked B1/B2/B3 execution rules.

    permit_gate is generated by M4 preflight for the matching frozen managed
    session, source and M3 feature proof. No immutable historical source edits.
    """
    if mode not in {"B1", "B2", "B3"} or case not in CASES:
        raise ValueError("TRIAL_UNDECLARED: mode or cost case not preregistered")
    if permit_gate.status != "PASS" or permit_gate.permit is None:
        raise ValueError("PERMIT_REQUIRED: no successful frozen preflight")
    permit = RunPermitV1.model_validate(permit_gate.permit.model_dump(mode="json"))
    expected_source = dukascopy_feature_contract(permit.session_id).dataset.model_dump(mode="json")
    source_digest = hashlib.sha256(json.dumps(
        expected_source, sort_keys=True, separators=(",", ":"), allow_nan=False
    ).encode()).hexdigest()
    if permit.identity.source_sha256 != source_digest:
        raise ValueError("SOURCE_IDENTITY_CONFLICT: permit names wrong vendor")
    if not (mode.lower() in permit.trial_id.lower()
            and case.lower() in permit.trial_id.lower()):
        raise ValueError("TRIAL_UNDECLARED: case lacks separate permit trial ID")
    if (permit.identity.engine_version != ENGINE_VERSION
        or permit.live_order_authority is not False
        or permit.identity.engine != "ml4t.backtest"):
        raise ValueError("ENGINE_EXECUTION_INVALID: research-only version-pin required")
    if (not frame.height or frame["symbol"].unique().to_list() != [DATA_SYMBOL]
        or frame["asset"].unique().to_list() != [DATA_SYMBOL]
        or frame["clock"].max() != "15:14"
        or frame["clock"].min() != "08:30"):
        raise ValueError("DATA_SESSION_MISMATCH: source or cutoff invalid")
    fee, slip = CASES[case]
    config = BacktestConfig(
        initial_cash=INITIAL_CASH, allow_short_selling=False, allow_leverage=True,
        fixed_margin_schedule={DATA_SYMBOL: (25_000.0, 20_000.0)},
        execution_mode=ExecutionMode.NEXT_BAR,
        fill_ordering=FillOrdering.EXIT_FIRST,
        stop_fill_mode=StopFillMode.STOP_PRICE,
        commission_type=CommissionType.PER_CONTRACT if fee else CommissionType.NONE,
        commission_per_share=fee,
        slippage_type=SlippageType.FIXED if slip else SlippageType.NONE,
        slippage_fixed=slip,
    )
    spec = ContractSpec(
        symbol=DATA_SYMBOL, asset_class=AssetClass.FUTURE,
        multiplier=HYPOTHETICAL_MULTIPLIER, tick_size=TICK, margin=25_000.0,
    )
    # FUTURE is the engine's hypothetical USD/point settlement adapter,
    # NOT a claim about the CFD's actual tradable contract or CME volume.
    strategy = DukascopyClockStrategy(mode)
    result = LegalLimitsEngine(
        DataFeed(
            prices_df=frame.select(
                "timestamp", "asset", "open", "high", "low", "close", "volume"
            ),
            signals_df=frame.select(
                "timestamp", "asset", "or_high", "prior_close", "vwap",
                "adx", "prior_adx", "next_tp", "next_sl"
            ),
        ),
        strategy, config, contract_specs={DATA_SYMBOL: spec},
    ).run()
    fills = result.to_fills_dataframe()
    trades = result.to_trades_dataframe()
    equity = result.to_equity_dataframe()
    # Fail if native produced any illegal passive fill or an overnight close.
    if fills.filter(
        (pl.col("order_type") == "limit") &
        (pl.col("side") == "sell") &
        (pl.col("price") + 1e-8 < pl.col("limit_price"))
    ).height:
        raise ValueError("ENGINE_EXECUTION_INVALID: illegal sell-limit fill")
    return HistoricalNativeResult(
        status="SIMULATED_NOT_LIVE_QUALIFIED", mode=mode, case=case,
        fills=fills, trades=trades, equity=equity,
        signals=tuple(strategy.signal_log),
        limitations=(
            "Dukascopy CFD price and quote volume, not NQ.F or CME traded volume.",
            "USD/point multiplier and fees are illustrative, not broker verified.",
            "Historical synthetic/native OCO is not live atomic broker OCO.",
            "All 2026 historical results already observed, not untouched holdout.",
        )
    )

def run_managed_dukascopy(
    root: str | Path, source_path: str | Path,
    intent: RunIntentV1 | dict[str, Any], *,
    mode: str, case: str, start: date, end: date
) -> HistoricalNativeResult:
    """Only public execution entry: pinned source -> M2 -> M3 -> M4 -> native M6.

    This cannot re-freeze or repair the original v1 session; a separate,
    already frozen managed session with fine-grained mode/cost trial IDs is needed.
    """
    parsed = RunIntentV1.model_validate(intent)
    contract: ResearchContractV1 = dukascopy_feature_contract(parsed.session_id)
    source = checked_source(source_path)
    prepared, computation = features_for_legacy_rules(source, contract)
    gate = preflight_run(str(root), parsed, computation, source, contract)
    if gate.status != "PASS":
        raise ValueError(f"{gate.reason_code}: {gate.next_safe_action}")
    bars, report = strict_sessions(prepared, start, end)
    if bars.is_empty():
        raise ValueError("DATA_SESSION_MISMATCH: no complete source sessions")
    if report["source_sha256"] != hashlib.sha256(Path(source_path).read_bytes()).hexdigest():
        raise ValueError("IDENTITY_DRIFT: source changed after verification")
    return _execute_registered_dukascopy(
        bars, mode=mode, case=case, permit_gate=gate
    )
